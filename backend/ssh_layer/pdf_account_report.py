def _make_accounts_hbar(accounts: list, path: str, top_n: int = 10) -> bool:
    top = accounts[:top_n]
    if not top:
        return False
    labels = [a['account'] for a in reversed(top)]
    values = [a['hours'] or 0 for a in reversed(top)]
    clrs   = CHART_COLORS[:len(labels)]
