def _make_accounts_donut(accounts: list, path: str, top_n: int = 8) -> bool:
    top = accounts[:top_n]
    if not top:
        return False
    labels = [a['account'] for a in top]
    values = [a['hours'] or 0 for a in top]
    if sum(values) == 0:
        return False
    import numpy as np
    clrs = CHART_COLORS[:len(labels)]
    fig, ax = plt.subplots(figsize=(7, 7), dpi=300)
    wedges, _ = ax.pie(
        values, colors=clrs, startangle=90, radius=0.85,
        wedgeprops={"width": 0.60, "edgecolor": "white", "linewidth": 2}
    )
    ax.set_aspect("equal")
    total = sum(values)
    for wedge, label, value in zip(wedges, labels, values):
        pct = value / total * 100
        if 0 < pct < 1.5:
            angle = (wedge.theta2 + wedge.theta1) / 2
            x = np.cos(np.deg2rad(angle))
            y = np.sin(np.deg2rad(angle))
            ax.annotate(
                f"{label} ({pct:.1f}%)",
                xy=(x * 0.80, y * 0.80), xytext=(x * 2.70, y * 1.05),
                arrowprops=dict(arrowstyle="-", color="#555555", lw=1),
                fontsize=8, color="#333333"
            )
    legend_labels = [f"{label} — {value:,.1f} hrs" for label, value in zip(labels, values)]
    ax.legend(
        wedges, legend_labels, loc="center left", bbox_to_anchor=(1.0, 0.5),
        frameon=False, fontsize=9.5, labelspacing=1.1,
        handlelength=1.4, handleheight=1.4
    )
    ax.set_title("Account Share of Total CPU Hours", fontsize=11,
                 fontweight="bold", color="#1a3a5c", pad=14)
    plt.tight_layout()
    plt.savefig(path, dpi=300, bbox_inches="tight", facecolor="white")
    plt.close()
    return True
